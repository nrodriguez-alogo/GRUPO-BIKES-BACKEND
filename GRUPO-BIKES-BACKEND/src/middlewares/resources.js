import multer from "multer";
import path from "node:path";
import { mkdir, writeFile, unlink } from "node:fs/promises";
import { randomUUID } from "node:crypto";
import { IMAGE_ROOT } from "../config.js";
import { fail } from "../ayudas/validacion.js";
const upload = multer({
  storage: multer.memoryStorage(),
  limits: {
    fileSize: 5 * 1024 * 1024,
    files: 1,
    fields: 20,
    fieldSize: 40000,
    parts: 22,
  },
  fileFilter: (req, file, cb) => {
    if (!["image/jpeg", "image/png", "image/webp"].includes(file.mimetype))
      return cb(
        Object.assign(new Error("Usa una imagen JPG, PNG o WebP."), {
          status: 400,
        }),
      );
    cb(null, true);
  },
}).single("imagen");
function imageType(b) {
  if (
    b.length >= 8 &&
    b.subarray(0, 8).equals(Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]))
  )
    return "png";
  if (b.length >= 3 && b[0] === 255 && b[1] === 216 && b[2] === 255)
    return "jpg";
  if (
    b.length >= 12 &&
    b.toString("ascii", 0, 4) === "RIFF" &&
    b.toString("ascii", 8, 12) === "WEBP"
  )
    return "webp";
  return null;
}
export function receiveImage(req, res, next) {
  upload(req, res, (error) => {
    if (error) return next(error);
    if (req.file) {
      const type = imageType(req.file.buffer);
      if (
        !type ||
        { jpg: "image/jpeg", png: "image/png", webp: "image/webp" }[type] !==
          req.file.mimetype
      )
        return next(
          Object.assign(new Error("El archivo no es una imagen compatible."), {
            status: 400,
          }),
        );
      req.file.extension = type;
    }
    next();
  });
}
export async function storeImage(req, folder = "") {
  if (!req.file) fail(400, "Selecciona una imagen.");
  const filename = randomUUID() + "." + req.file.extension;
  const relative = folder ? folder + "/" + filename : filename;
  await mkdir(path.join(IMAGE_ROOT, folder), { recursive: true });
  await writeFile(path.join(IMAGE_ROOT, relative), req.file.buffer, {
    flag: "wx",
  });
  req.savedImage = relative;
  return relative;
}
export async function removeImage(relative) {
  // Only files generated by this application are eligible for automatic cleanup.
  if (
    typeof relative !== "string" ||
    !/^(usuarios\/)?[a-f0-9-]{36}\.(png|jpg|webp)$/.test(relative)
  )
    return;
  await unlink(path.join(IMAGE_ROOT, relative)).catch(() => {});
}
export const uploadImage = receiveImage;
export const uploadUserImage = receiveImage;
export const uploadSingleImage = receiveImage;
